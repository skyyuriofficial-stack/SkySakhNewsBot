def api(method, payload):
    r = requests.post(f"https://api.telegram.org/bot{TOKEN}/{method}", json=payload, timeout=30)
    r.raise_for_status()
    data = r.json()
    if not data.get("ok"):
        raise RuntimeError(data)
    return data

try:
    result = api("deleteMessage", {"chat_id": CHAT_ID, "message_id": BAD_MESSAGE_ID})
    print("DELETED_BAD_MESSAGE=", BAD_MESSAGE_ID, result.get("ok"))
except Exception as exc:
    print("DELETE_BAD_MESSAGE_FAILED=", repr(exc))

